def main() -> int:
    if not os.path.isfile(PCB):
        print(f"missing {PCB}", file=sys.stderr)
        return 1
    board = pcbnew.LoadBoard(PCB)
    j2 = board.FindFootprintByReference("J2")
    if j2 is None:
        print("missing J2", file=sys.stderr)
        return 1
    _, jy, _ = mm_xy(j2)
    if jy > 0:
        print(f"already spun: J2 is at y={jy} (phone-top). Not rotating again.")
        return 1
    before = {ref: mm_xy(board.FindFootprintByReference(ref))
              for ref in KEY_REFS
              if board.FindFootprintByReference(ref) is not None}
    rotate_board(board)
    board.BuildListOfNets()
    refill(board)
    pcbnew.SaveBoard(PCB, board)
    refresh_placement(board)
    print("rotated board 180° around the magnet origin; copper kept")
    for ref, old in before.items():
        fp = board.FindFootprintByReference(ref)
        new = mm_xy(fp)
        print(f"  {ref:4s}  {old}  ->  {new}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
