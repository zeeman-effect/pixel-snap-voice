#!/usr/bin/env python
"""Spin the live board 180° around the magnet origin.

Puts J2 at the camera / phone-top end and SW1 on the phone-left wall. The
tray, ring, and 6 o'clock clocking magnet stay put. Does not wipe copper.
Do not confuse this with generate_pcb.py.

Run with the KiCad 10 interpreter:

    /c/Users/zachr/AppData/Local/Programs/KiCad/10.0/bin/python.exe apply_lid_180.py
"""

from __future__ import annotations

import json
import os
import sys

import pcbnew

try:
    import wx
except ImportError:
    wx = None
else:
    wx.DisableAsserts()

HERE = os.path.dirname(os.path.abspath(__file__))
PCB = os.path.join(HERE, "recorder.kicad_pcb")
PLACEMENT = os.path.join(HERE, "placement.json")
ORIGIN = pcbnew.VECTOR2I(0, 0)
TURN = pcbnew.EDA_ANGLE(180, pcbnew.DEGREES_T)
KEY_REFS = ("J2", "SW1", "MK1", "U1", "BT1", "J3", "D1")


def mm_xy(fp) -> tuple[float, float, float]:
    return (
        round(pcbnew.ToMM(fp.GetPosition().x), 3),
        round(pcbnew.ToMM(fp.GetPosition().y), 3),
        round(fp.GetOrientationDegrees()) % 360,
    )


def rotate_item(item) -> None:
    locked = False
    if hasattr(item, "IsLocked"):
        locked = item.IsLocked()
        if locked:
            item.SetLocked(False)
    item.Rotate(ORIGIN, TURN)
    if locked:
        item.SetLocked(True)


def rotate_board(board) -> None:
    for fp in list(board.GetFootprints()):
        rotate_item(fp)
        ref = fp.Reference()
        if ref is not None and ref.IsVisible():
            ref.SetTextAngle(pcbnew.EDA_ANGLE(0, pcbnew.DEGREES_T))
    for track in list(board.GetTracks()):
        rotate_item(track)
    for zone in list(board.Zones()):
        rotate_item(zone)
    for drawing in list(board.GetDrawings()):
        rotate_item(drawing)
    areas = board.GetRuleAreas() if hasattr(board, "GetRuleAreas") else []
    for area in list(areas):
        rotate_item(area)


def refill(board) -> None:
    pcbnew.ZONE_FILLER(board).Fill(board.Zones())


def refresh_placement(board) -> None:
    with open(PLACEMENT, encoding="utf-8") as fh:
        data = json.load(fh)
    rows = {row["ref"]: row for row in data.get("parts", [])}
    for live in board.GetFootprints():
        ref = live.GetReference()
        row = rows.get(ref)
        if row is None:
            continue
